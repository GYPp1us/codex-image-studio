const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs/promises');

async function panels(page){
  await page.emulateMedia({colorScheme:'dark'});
  const screenshots=process.env.STUDIO_QA_SCREENSHOTS;
  async function capture(name){
    if(!screenshots)return;
    await page.locator('#toast .toast').waitFor({state:'hidden'});
    await fs.mkdir(screenshots,{recursive:true});
    await page.screenshot({path:path.join(screenshots,name+'.png'),animations:'disabled'});
  }
  const destination=page.locator('.composer-destination');
  await destination.click();
  await page.locator('.pick-row[data-id="tpl-A"]').click();
  await page.waitForFunction(()=>document.querySelector('[data-pick="confirm"]')?.disabled===false,null,{polling:50});
  await page.locator('[data-pick="confirm"]').tap();
  await page.waitForFunction(()=>document.querySelector('.composer-destination strong')?.textContent==='A');
  assert.equal(await page.locator('#into [data-dir=save-target]').count(),0);
  assert.equal(await destination.evaluate(b=>b.getBoundingClientRect().top>=document.querySelector('#prompt').getBoundingClientRect().bottom),true);
  await capture('01-compose');
  await page.locator('[data-act=tab][data-tab=works]').click();
  const tab=key=>page.locator('#works-seg [data-v="'+key+'"]');
  const group=page.locator('.dir-card[data-id=tpl-A]');
  await group.waitFor();
  assert.equal(await page.locator('#page h1').textContent(),'作品');
  assert.equal(await tab('generated').textContent(),'图库');
  assert.equal(await page.locator('#dir-path').count(),0);
  await capture('02-gallery');
  await page.evaluate(()=>{window.panelMotions=[];const animate=Element.prototype.animate;
    Element.prototype.animate=function(frames,options){
      if(this.matches('#page .scroll')&&frames[0]?.transform?.startsWith('translateX'))window.panelMotions.push(frames[0].transform);
      return animate.call(this,frames,options);
    };
  });
  await tab('references').click();await tab('favorites').click();await tab('generated').click();
  await group.click();await page.locator('#dir-path [data-id=""]').click();
  await group.waitFor();
  assert.deepEqual(await page.evaluate(()=>window.panelMotions.slice(-5)),['translateX(16px)','translateX(16px)','translateX(-16px)','translateX(16px)','translateX(-16px)']);
  const scroll=page.locator('.dir-scroll');
  await scroll.evaluate(el=>{el.scrollTop=440;});
  const anchor=await scroll.evaluate(el=>el.scrollTop);
  assert.ok(anchor>300);
  const point=await scroll.evaluate(el=>{
    const box=el.getBoundingClientRect();
    const x=box.left+box.width*.25,y=box.top+box.height*.5;
    return {x,y,id:document.elementFromPoint(x,y)?.closest('.dir-card')?.dataset.id};
  });
  assert.ok(point.id,'visible folder at the tap point');
  await page.touchscreen.tap(point.x,point.y);
  await page.waitForFunction(id=>S.coll===id,point.id);
  await page.locator('[data-dir=up]').click();
  await page.waitForFunction(y=>Math.abs(document.querySelector('.dir-scroll').scrollTop-y)<4,anchor);
  await scroll.evaluate(el=>{el.scrollTop=0;});
  await group.click();
  const tiles=page.locator('#grid .tile');
  await tiles.first().click({modifiers:['Control']});
  await page.locator('[data-selection=menu]').click();
  assert.equal(await page.locator('.sheet [data-selection=unfavorite]').count(),0);
  await capture('03-selection');
  await page.locator('.sheet [data-selection=favorite]').click();
  await page.locator('#selection-toolbar').waitFor({state:'detached'});
  await tiles.first().click({modifiers:['Control']});
  await page.locator('[data-selection=menu]').click();
  assert.equal(await page.locator('.sheet [data-selection=favorite]').count(),0);
  await page.getByRole('dialog').last().getByRole('button',{name:'关闭'}).click();
  await tiles.nth(1).click();
  await page.locator('[data-selection=menu]').click();
  await page.locator('[data-selection=favorite]').filter({hasText:'1 张未收藏'}).waitFor();
  await page.locator('[data-selection=unfavorite]').filter({hasText:'1 张已收藏'}).waitFor();
  await page.getByRole('dialog').last().getByRole('button',{name:'关闭'}).click();
  await page.locator('[data-selection=exit]').click();
  await tiles.first().click();
  await page.locator('#viewer [data-act=v-more]').click();
  await page.locator('.art-shortcuts [data-dir=single-move]').waitFor();
  assert.equal(await page.locator('.art-actions [data-act=reconnect]').isVisible(),false);
  assert.equal(await page.locator('.art-actions [data-act=im-del]').count(),1);
  await capture('04-art-actions');
  await page.locator('.art-shortcuts [data-dir=single-move]').click();
  await page.locator('[data-pick=new]').click();
  await page.locator('.dir-form input').fill('封面候选');
  await page.locator('.dir-form [type=submit]').click();
  await page.locator('.dir-form').waitFor({state:'detached'});
  await page.locator('#viewer [data-act=v-back]').click();
  await page.locator('[data-dir=up]').click();
  await page.locator('#page [data-dir=create]').click();
  await page.locator('.dir-form input').fill('常用目录');
  await page.locator('.dir-form [type=submit]').click();
  await page.locator('.dir-card').filter({hasText:'常用目录'}).waitFor();
  await group.click();
  await tiles.first().click();
  await page.locator('#viewer [data-act=v-more]').click();
  await page.locator('.art-shortcuts [data-dir=single-move]').click();
  await page.locator('.dir-picker-path [data-id=""]').click();
  await page.locator('.pick-shortcut').filter({hasText:'封面候选'}).waitFor();
  const recentId=await page.locator('.pick-shortcut').filter({hasText:'常用目录'}).getAttribute('data-id');
  assert.equal(await page.locator('.pick-row[data-id="'+recentId+'"]').count(),0);
  assert.equal(await page.locator('.pick-footer small').textContent(),'请在「A」内选择');
  await capture('05-location');
  await page.locator('.pick-search input').fill('封面候选');
  await page.locator('.pick-row').filter({hasText:'封面候选'}).waitFor();
  assert.equal(await page.locator('.pick-shortcut').count(),0);
  assert.equal(await page.locator('[data-pick=confirm]').isDisabled(),true);
  await page.getByRole('dialog').last().getByRole('button',{name:'关闭'}).click();
  await page.locator('#viewer [data-act=v-back]').click();
  await page.locator('[data-dir=up]').click();
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>RM===true);
  const before=await page.evaluate(()=>window.panelMotions.length);
  await tab('favorites').click();
  assert.equal(await page.evaluate(()=>window.panelMotions.length),before);
  console.log('Passed destination layout, gallery titles, directional and reduced motion, three favorite states, artwork menu and folder picker.');
}
module.exports={panels};
